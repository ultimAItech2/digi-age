"""Pack the rendered frames into the atlases the game loads (tools/sprites).

    python3 tools/sprites/pack.py

Reads builds/sprites/<kind>/ (tools/sprites/render.py) and writes, per kind,
assets/sprites/rendered/<kind>.png (colour) and <kind>_mask.png (the faction
colour mask), plus scripts/sprite_atlas_data.gd: the frame grid, scale, anchor
and animation table DASprites reads. Building and deposit atlases are one row
of states; unit atlases have one row per facing and one column per frame.
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'builds' / 'sprites'
OUT = ROOT / 'assets' / 'sprites' / 'rendered'
DATA = ROOT / 'scripts' / 'sprite_atlas_data.gd'
LIMIT = 4096          # widest building, deposit or scenery atlas; their states wrap onto rows
UNIT_LIMIT = 6144     # widest unit atlas
MAIN = {'buildings': 'complete', 'props': 'full', 'units': '0_idle_0', 'scenery': 'v0'}


def gd(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, str):
        return '"%s"' % value
    if isinstance(value, (list, tuple)):
        return '[' + ', '.join(gd(v) for v in value) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join('%s: %s' % (gd(k), gd(v)) for k, v in value.items()) + '}'
    return repr(value)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    table = {}
    for folder in sorted(p for p in SRC.iterdir() if (p / 'meta.json').exists()):
        meta = json.loads((folder / 'meta.json').read_text())
        labels = meta['labels']
        if not all((folder / ('%03d.png' % i)).exists() for i in range(len(labels))):
            print('skip %s: frames missing (rendered with --still?)' % meta['kind'])
            continue
        width, height = meta['frame']
        rows = meta['directions']
        cols = len(labels) // rows
        if rows == 1 and cols * width > LIMIT:
            # States wrap onto further rows so no atlas side passes the limit.
            cols = max(1, LIMIT // width)
            rows = (len(labels) + cols - 1) // cols
        colour = Image.new('RGBA', (cols * width, rows * height), (0, 0, 0, 0))
        mask = Image.new('L', (cols * width, rows * height), 0)
        for index in range(len(labels)):
            cell = ((index % cols) * width, (index // cols) * height)
            colour.paste(Image.open(folder / ('%03d.png' % index)).convert('RGBA'), cell)
            mask.paste(Image.open(folder / ('%03d_mask.png' % index)).convert('L'), cell)
        ppu = float(meta['ppu'])
        anchor = meta['anchor']
        shrink = 1.0
        if cols * width > UNIT_LIMIT:
            # A unit atlas keeps its facings-by-frames grid; the largest ones are scaled down to fit instead.
            new_w = UNIT_LIMIT // cols
            shrink = new_w / width
            new_h = round(height * shrink)
            colour = colour.resize((cols * new_w, rows * new_h), Image.LANCZOS)
            mask = mask.resize((cols * new_w, rows * new_h), Image.LANCZOS)
            ppu *= shrink
            anchor = round(anchor * shrink)
            width, height = new_w, new_h
        colour.save(OUT / (meta['kind'] + '.png'), optimize=True)
        mask.save(OUT / (meta['kind'] + '_mask.png'), optimize=True)
        # The opaque box of the main frame: what a click can hit and where the health bar sits.
        # Half-transparent pixels (the feathered ground around a building) are not part of it.
        main_index = labels.index(MAIN[meta['group']])
        box = Image.open(folder / ('%03d.png' % main_index)).convert('RGBA').getchannel('A').point(lambda a: 255 if a > 128 else 0).getbbox()
        box = [round(v * shrink) for v in box]
        anims = {}
        start = 0
        for name, spec in meta['anims'].items():
            anims[name] = [start, spec['frames'], spec['fps']]
            start += spec['frames']
        table[meta['kind']] = {
            'group': meta['group'], 'cells': meta['cells'], 'large': meta['large'], 'ppu': round(ppu, 3),
            'frame': [width, height], 'anchor': anchor, 'cols': cols, 'rows': rows,
            'main': [main_index % cols, main_index // cols], 'box': list(box), 'anims': anims,
            'states': labels if meta['directions'] == 1 else [],
        }
        print('%s: %dx%d atlas, %d x %d frames' % (meta['kind'], colour.width, colour.height, cols, rows))
    lines = ['class_name DASpriteAtlasData', 'extends RefCounted',
             '## Generated by tools/sprites/pack.py from the Blender renders. Do not edit by hand.',
             '## frame and box are pixels, anchor is the origin row above the frame bottom,',
             '## anims are [first column, frames, frames per second].', 'const KINDS = {']
    for kind, entry in table.items():
        lines.append('\t%s: %s,' % (gd(kind), gd(entry)))
    lines.append('}')
    DATA.write_text('\n'.join(lines) + '\n')
    print('wrote %s (%d kinds)' % (DATA.relative_to(ROOT), len(table)))


main()
